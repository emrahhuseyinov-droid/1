export function translateSiteText(value: string, language: SiteLanguage): string {
  if (!value.trim()) return value

  const leadingWhitespace = value.match(/^\s*/)?.[0] ?? ''
  const trailingWhitespace = value.match(/\s*$/)?.[0] ?? ''
  const key = value.trim().replace(/\s+/g, ' ')

  if (language === 'en') {
    const exactEnglish = enPhrases.get(key)
    if (exactEnglish) return `${leadingWhitespace}${exactEnglish}${trailingWhitespace}`

    const sectionTitle = key.match(/^(.+) \| pepe\.casa$/i)
    if (sectionTitle) {
      const englishSection = enPhrases.get(sectionTitle[1])
      if (englishSection) return `${leadingWhitespace}${englishSection} | pepe.casa${trailingWhitespace}`
    }

    return value
  }

  const exact = ruPhrases.get(key)
  if (exact) return `${leadingWhitespace}${exact}${trailingWhitespace}`

  const dynamic = translateDynamicPhrase(key)
  if (dynamic) return `${leadingWhitespace}${dynamic}${trailingWhitespace}`

  const wordTranslation = ruWords[key.toLowerCase()]
  if (wordTranslation !== undefined) {
    const translated = /^[A-Z]/.test(key)
      ? wordTranslation.charAt(0).toUpperCase() + wordTranslation.slice(1)
      : wordTranslation
    return `${leadingWhitespace}${translated}${trailingWhitespace}`
  }

  return value
}
